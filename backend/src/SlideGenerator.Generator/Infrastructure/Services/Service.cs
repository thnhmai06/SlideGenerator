    /// <summary>
    ///     Handles a WorkflowCore lifecycle event for a single job instance. <c>async void</c> is
    ///     deliberate here — <see cref="IWorkflowHost.OnLifeCycleEvent" /> is a synchronous event, and
    ///     resolving <see cref="JobPersistContext.RequestId" /> for the job needs an async persistence
    ///     lookup. Exceptions are caught locally, so a lookup failure can't crash the process.
    /// </summary>
    // ReSharper disable once AsyncVoidMethod
    private async void HandleLifeCycleEvent(LifeCycleEvent e)
    {
        string jobId;
        Status status;
        switch (e)
        {
            case WorkflowStarted ws:
                jobId = ws.WorkflowInstanceId;
                status = Status.Running;
                break;
            case WorkflowCompleted wc:
                jobId = wc.WorkflowInstanceId;
                status = Status.Complete;
                break;
            case WorkflowError we:
                jobId = we.WorkflowInstanceId;
                status = Status.Error;
                break;
            default:
                return;
        }

        var requestId = jobId;
        try
        {
            var instance = await persistence.GetWorkflowInstance(jobId, CancellationToken.None).ConfigureAwait(false);
            if (instance?.Data is JobContext jobContext) requestId = jobContext.Persist.RequestId;
        }
        catch (Exception ex)
        {
            logger.LogWarning(ex, "Failed to resolve RequestId for job {JobId} lifecycle event.", jobId);
        }

        eventBus.Publish(new JobProgress
        {
            RequestId = requestId,
            JobId = jobId,
            Status = status,
            Timestamp = DateTimeOffset.UtcNow
        });
    }

    /// <summary>
    ///     Deletes a single completed/terminated <c>Workflow</c> row and its dependents. Column/join shape
    ///     matches WorkflowCore's actual SQLite schema (verified against a live <c>Workflows.db</c>):
    ///     <c>Workflow.InstanceId</c> (TEXT, the GUID job id) — not <c>Id</c>, which doesn't exist on this
    ///     table; <c>ExecutionPointer.WorkflowId</c>/<c>ExtensionAttribute.ExecutionPointerId</c> are
    ///     INTEGER FKs to the referenced row's <c>PersistenceId</c> — not the GUID/TEXT id; only
    ///     <c>ExecutionError.WorkflowId</c> is a loose TEXT column holding the GUID directly (no FK
    ///     declared on it at all), so it needs no join.
    /// </summary>
    private static async Task<int> DeleteInstanceAsync(
        SqliteConnection conn, SqliteTransaction tx, string instanceId, CancellationToken ct)
    {
        await DeleteExtensionAttributesAsync(conn, tx, instanceId, ct).ConfigureAwait(false);
        await DeleteExecutionErrorsAsync(conn, tx, instanceId, ct).ConfigureAwait(false);
        await DeleteExecutionPointersAsync(conn, tx, instanceId, ct).ConfigureAwait(false);

        await using var cmd = conn.CreateCommand();
        cmd.Transaction = tx;
        cmd.CommandText =
            $"DELETE FROM \"Workflow\" WHERE \"InstanceId\" = @id AND \"Status\" IN ({(int)WorkflowStatus.Complete}, {(int)WorkflowStatus.Terminated})";
        cmd.Parameters.AddWithValue("@id", instanceId);
        return await cmd.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
    }

    private static async Task DeleteExtensionAttributesAsync(
        SqliteConnection conn, SqliteTransaction tx, string instanceId, CancellationToken ct)
    {
        await using var cmd = conn.CreateCommand();
        cmd.Transaction = tx;
        cmd.CommandText =
            "DELETE FROM \"ExtensionAttribute\" WHERE \"ExecutionPointerId\" IN (" +
            "SELECT ep.\"PersistenceId\" FROM \"ExecutionPointer\" ep " +
            "INNER JOIN \"Workflow\" w ON w.\"PersistenceId\" = ep.\"WorkflowId\" " +
            "WHERE w.\"InstanceId\" = @id)";
        cmd.Parameters.AddWithValue("@id", instanceId);
        await cmd.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
    }

    private static async Task DeleteExecutionErrorsAsync(
        SqliteConnection conn, SqliteTransaction tx, string instanceId, CancellationToken ct)
    {
        await using var cmd = conn.CreateCommand();
        cmd.Transaction = tx;
        cmd.CommandText = "DELETE FROM \"ExecutionError\" WHERE \"WorkflowId\" = @id";
        cmd.Parameters.AddWithValue("@id", instanceId);
        await cmd.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
    }

    private static async Task DeleteExecutionPointersAsync(
        SqliteConnection conn, SqliteTransaction tx, string instanceId, CancellationToken ct)
    {
        await using var cmd = conn.CreateCommand();
        cmd.Transaction = tx;
        cmd.CommandText =
            "DELETE FROM \"ExecutionPointer\" WHERE \"WorkflowId\" IN (" +
            "SELECT \"PersistenceId\" FROM \"Workflow\" WHERE \"InstanceId\" = @id)";
        cmd.Parameters.AddWithValue("@id", instanceId);
        await cmd.ExecuteNonQueryAsync(ct).ConfigureAwait(false);
    }

    private async Task<Summary> ToSummaryAsync(
        string requestId, IReadOnlyList<WorkflowInstance> jobs, CancellationToken ct)
    {
        var status = DeriveStatus(jobs);
        // ListGroupsAsync only ever produces groups from instances whose Data is JobContext, so this cast
        // is guaranteed to succeed for every job in the group.
        var first = (JobContext)jobs[0].Data;
        var createdAt = jobs.Min(j => j.CreateTime);
        var completedAt = status is Status.Complete or Status.Cancelled
            ? jobs.Max(j => j.CompleteTime ?? j.CreateTime)
            : (DateTime?)null;

        var requestProgress = await studioRepository.GetRequestAsync(requestId, ct).ConfigureAwait(false);
        var jobProgress = await studioRepository.GetJobsAsync(requestId, ct).ConfigureAwait(false);
        var logEntries = logFileReader.ReadAll(first.Persist.LogPath);

        var jobSummaries = new Dictionary<string, JobSummary>();
        foreach (var job in jobs)
            jobSummaries[job.Id] = await ToJobSummaryAsync(requestId, job, jobProgress, logEntries, ct)
                .ConfigureAwait(false);

        return new Summary
        {
            Request = first.Persist.Request,
            Status = status,
            Phase = requestProgress?.Phase,
            CreatedAt = new DateTimeOffset(createdAt, TimeSpan.Zero),
            CompletedAt = completedAt.HasValue ? new DateTimeOffset(completedAt.Value, TimeSpan.Zero) : null,
            Logs = logEntries.Where(e => e.Path == requestId).ToList(),
            Jobs = jobSummaries
        };
    }

    private async Task<JobSummary> ToJobSummaryAsync(
        string requestId, WorkflowInstance job, IReadOnlyDictionary<string, JobProgress> jobProgress,
        IReadOnlyList<LogEntry> logEntries, CancellationToken ct)
    {
        var outputPath = (job.Data as JobContext)?.Persist.Specification.OutputPath ?? string.Empty;
        var status = jobProgress.TryGetValue(job.Id, out var jp) ? jp.Status : ToJobStatus(job.Status);
        var jobScopePrefix = $"{requestId}/{job.Id}";

        var rowProgress = await studioRepository.GetRowsAsync(requestId, job.Id, ct).ConfigureAwait(false);
        var rowSummaries = rowProgress.ToDictionary(kv => kv.Key, kv => new RowSummary
        {
            Status = kv.Value.Status,
            Stage = kv.Value.Stage,
            Note = kv.Value.Note,
            Timestamp = kv.Value.Timestamp,
            Logs = logEntries.Where(e => e.Path == $"{jobScopePrefix}/{kv.Key}").ToList()
        });

        return new JobSummary
        {
            Status = status,
            OutputPath = outputPath,
            CompletedAt = job.CompleteTime.HasValue
                ? new DateTimeOffset(job.CompleteTime.Value, TimeSpan.Zero)
                : null,
            Rows = rowSummaries,
            Logs = logEntries
                .Where(e => e.Path == jobScopePrefix || e.Path.StartsWith(jobScopePrefix + "/", StringComparison.Ordinal))
                .ToList()
        };
    }

    private static Status ToJobStatus(WorkflowStatus status) => status switch
    {
        WorkflowStatus.Runnable => Status.Running,
        WorkflowStatus.Suspended => Status.Paused,
        WorkflowStatus.Terminated => Status.Cancelled,
        _ => Status.Complete
    };

    internal static Status DeriveStatus(IReadOnlyList<WorkflowInstance> jobs)
    {
        if (jobs.Any(j => j.Status == WorkflowStatus.Runnable)) return Status.Running;
        if (jobs.Any(j => j.Status == WorkflowStatus.Suspended)) return Status.Paused;
        if (jobs.All(j => j.Status == WorkflowStatus.Terminated)) return Status.Cancelled;
        return Status.Complete;
    }

    private static string ResolveWorkflowLogPath(Request request)
    {
        var fileName = Naming.SanitizeFileName(request.Name);
        if (string.IsNullOrWhiteSpace(fileName)) fileName = "workflow";
        return Path.Combine(NameAndPaths.LogsFolder.WorkflowPath, $"{fileName}.log");
    }
