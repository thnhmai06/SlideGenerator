namespace SlideGenerator.Generator.Infrastructure.Services;

/// <summary>
///     Implements <see cref="IService" /> by wrapping the WorkflowCore
///     <see cref="IWorkflowHost" /> and <see cref="IWorkflowController" />.
///     Lives in Infrastructure because it has a direct dependency on the WorkflowCore framework.
///     <c>StartAsync</c>'s spawn phase (reading the recipe, computing the job list, cleaning up nothing
///     shared) runs as plain code here — deliberately NOT a WorkflowCore workflow itself, so it is never
///     throttled by <c>WorkflowOptions.MaxConcurrentWorkflows</c> alongside the <see cref="JobWorkflow" />
///     instances it spawns.
/// </summary>
internal sealed class Service(
    IWorkflowHost workflowHost,
    IWorkflowController workflowController,
    IPersistenceProvider persistence,
    IEventBus eventBus,
    IRecipeRepository recipeRepository,
    IStudioRepository studioRepository,
    ILogFileReader logFileReader,
    WorkflowOptions workflowOptions,
    ISettingProvider settingProvider,
    ILogger<Service> logger)
    : IService
{
    private bool _isStarted;
    private LifeCycleEventHandler? _lifeCycleHandler;

    /// <inheritdoc />
    public async Task InitializeAsync(CancellationToken ct = default)
    {
        workflowHost.RegisterWorkflow<JobWorkflow, JobContext>();
        ApplyMaxConcurrentJobs();

        _lifeCycleHandler = HandleLifeCycleEvent;
        workflowHost.OnLifeCycleEvent += _lifeCycleHandler;

        await workflowHost.StartAsync(ct).ConfigureAwait(false);
        _isStarted = true;
        logger.LogInformation("WorkflowCore host started and JobWorkflow registered.");
    }

    /// <inheritdoc />
    public async Task ShutdownAsync(CancellationToken ct = default)
    {
        if (!_isStarted)
        {
            logger.LogDebug("WorkflowCore host was not started; skipping stop.");
            return;
        }

        if (_lifeCycleHandler is not null)
            workflowHost.OnLifeCycleEvent -= _lifeCycleHandler;

        await workflowHost.StopAsync(ct).ConfigureAwait(false);
        _isStarted = false;
        logger.LogInformation("WorkflowCore host stopped.");
    }

    /// <inheritdoc />
    public async Task<string> CreateAsync(Request request, CancellationToken ct = default)
    {
        using var scope = logger.BeginScope("Start/{RecipeId}/{RequestName}", request.RecipeId, request.Name);

        ApplyMaxConcurrentJobs();

        var entry = await recipeRepository.GetAsync(request.RecipeId, ct).ConfigureAwait(false)
                    ?? throw new InvalidOperationException($"Recipe {request.RecipeId} not found.");

        var requestId = Guid.NewGuid().ToString();
        var logPath = ResolveWorkflowLogPath(request);
        var jobs = BuildJobs(entry.Recipe, request);

        var conflictingPath = await FindConflictingOutputPathAsync(jobs).ConfigureAwait(false);
        if (conflictingPath is not null)
            throw new InvalidOperationException(
                $"Output path '{conflictingPath}' is already being generated by an active request.");

        eventBus.Publish(new RequestProgress
        {
            RequestId = requestId,
            Phase = RequestPhase.PreparationStarted,
            Timestamp = DateTimeOffset.UtcNow
        });
        eventBus.AnnounceExpectedJobCount(requestId, jobs.Count);

        foreach (var job in jobs)
        {
            var jobContext = new JobContext
            {
                Persist = new JobPersistContext
                {
                    RequestId = requestId,
                    Request = request,
                    Recipe = entry.Recipe,
                    LogPath = logPath,
                    Specification = job
                }
            };
            var jobId = await workflowHost.StartWorkflow(nameof(JobWorkflow), 1, jobContext).ConfigureAwait(false);
            eventBus.Publish(new JobProgress
            {
                RequestId = requestId,
                JobId = jobId,
                Status = Status.Pending,
                Timestamp = DateTimeOffset.UtcNow
            });
            logger.LogInformation("JobSpec spawned | JobId: {JobId} | OutputPath: {OutputPath}", jobId, job.OutputPath);
        }

        logger.LogInformation("Request started | RequestId: {RequestId} | Jobs: {Count}", requestId, jobs.Count);
        return requestId;
    }

    /// <inheritdoc />
    public async Task<PartialResult> StopAsync(string requestId, CancellationToken ct = default)
    {
        var jobs = await LoadGroupAsync(requestId).ConfigureAwait(false);
        return await FanOutAsync(requestId, jobs, WorkflowStatus.Runnable,
                workflowController.TerminateWorkflow, Status.Cancelled)
            .ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async Task<PartialResult> PauseAsync(string requestId, CancellationToken ct = default)
    {
        var jobs = await LoadGroupAsync(requestId).ConfigureAwait(false);
        return await FanOutAsync(requestId, jobs, WorkflowStatus.Runnable,
                workflowController.SuspendWorkflow, Status.Paused)
            .ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async Task<PartialResult> ResumeAsync(string requestId, CancellationToken ct = default)
    {
        var jobs = await LoadGroupAsync(requestId).ConfigureAwait(false);
        return await FanOutAsync(requestId, jobs, WorkflowStatus.Suspended,
                workflowController.ResumeWorkflow, Status.Running)
            .ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async Task<int> StopAllAsync(CancellationToken ct = default)
    {
        var actives = await ListActiveAsync(ct).ConfigureAwait(false);
        var count = 0;
        foreach (var requestId in actives.Keys)
        {
            var result = await StopAsync(requestId, ct).ConfigureAwait(false);
            if (result.Succeeded > 0) count++;
        }

        return count;
    }

    /// <inheritdoc />
    public async Task<int> PauseAllAsync(CancellationToken ct = default)
    {
        var actives = await ListActiveAsync(ct).ConfigureAwait(false);
        var count = 0;
        foreach (var requestId in actives.Where(kv => kv.Value.Status == Status.Running).Select(kv => kv.Key))
        {
            var result = await PauseAsync(requestId, ct).ConfigureAwait(false);
            if (result.Succeeded > 0) count++;
        }

        return count;
    }

    /// <summary>
    ///     Re-applies <c>Performance.MaxConcurrentJobs</c> from the current settings onto the running
    ///     WorkflowCore host's <c>MaxConcurrentWorkflows</c>. Called once at startup and opportunistically
    ///     at the start of every <see cref="CreateAsync" /> — <see cref="Service" /> reads
    ///     <see cref="ISettingProvider" /> itself rather than being told to re-apply externally.
    /// </summary>
    private void ApplyMaxConcurrentJobs()
    {
        var value = (int)settingProvider.Current.Performance.MaxConcurrentJobs;
        workflowOptions.UseMaxConcurrentWorkflows(value);
        logger.LogInformation("MaxConcurrentWorkflows set to {Value}.", value);
    }

    /// <inheritdoc />
    public async Task<IReadOnlyDictionary<string, Summary>> ListActiveAsync(CancellationToken ct = default)
    {
        var groups = await ListGroupsAsync().ConfigureAwait(false);
        var active = groups.Where(kv => DeriveStatus(kv.Value) is Status.Running or Status.Paused);
        return await ToSummariesAsync(active, ct).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async Task<IReadOnlyDictionary<string, Summary>> ListCompletedAsync(CancellationToken ct = default)
    {
        var groups = await ListGroupsAsync().ConfigureAwait(false);
        var completed = groups.Where(kv => DeriveStatus(kv.Value) is Status.Complete or Status.Cancelled);
        return await ToSummariesAsync(completed, ct).ConfigureAwait(false);
    }

    private async Task<IReadOnlyDictionary<string, Summary>> ToSummariesAsync(
        IEnumerable<KeyValuePair<string, IReadOnlyList<WorkflowInstance>>> groups, CancellationToken ct)
    {
        var result = new Dictionary<string, Summary>();
        foreach (var (requestId, jobs) in groups)
            result[requestId] = await ToSummaryAsync(requestId, jobs, ct).ConfigureAwait(false);
        return result;
    }

    /// <summary>
    ///     Returns the first output path among <paramref name="jobs" /> that collides with an output path
    ///     already claimed by a job of another active (running or paused) request — or
    ///     <see langword="null" /> if none collide. Same-recipe requests are otherwise allowed to run
    ///     concurrently; only an actual output-file clash is rejected.
    /// </summary>
    private async Task<string?> FindConflictingOutputPathAsync(IReadOnlyList<JobSpecification> jobs)
    {
        var groups = await ListGroupsAsync().ConfigureAwait(false);
        var activeOutputPaths = groups
            .Where(kv => DeriveStatus(kv.Value) is Status.Running or Status.Paused)
            .SelectMany(kv => kv.Value)
            .Select(wi => (wi.Data as JobContext)?.Persist.Specification.OutputPath)
            .Where(path => path is not null)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

        return jobs.Select(j => j.OutputPath).FirstOrDefault(activeOutputPaths.Contains);
    }

    /// <inheritdoc />
    public async Task<bool> DeleteAsync(string requestId, CancellationToken ct = default)
    {
        var jobs = await LoadGroupAsync(requestId).ConfigureAwait(false);
        if (jobs is null)
        {
            logger.LogWarning("Request {RequestId} not found — delete skipped.", requestId);
            return false;
        }

        if (DeriveStatus(jobs) is Status.Running or Status.Paused)
            await StopAsync(requestId, ct).ConfigureAwait(false);

        await studioRepository.DeleteRequestAsync(requestId, ct).ConfigureAwait(false);

        await using var conn = new SqliteConnection(NameAndPaths.DataFolder.WorkflowsFile.ConnectionString);
        await conn.OpenAsync(ct).ConfigureAwait(false);
        await using var tx = conn.BeginTransaction();
        try
        {
            var deleted = 0;
            foreach (var job in jobs)
                deleted += await DeleteInstanceAsync(conn, tx, job.Id, ct).ConfigureAwait(false);

            tx.Commit();
            logger.LogInformation("Deleted request {RequestId} ({Count} job(s)).", requestId, deleted);
            return deleted > 0;
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Failed to delete request | Reason: DB transaction error | RequestId: {RequestId}",
                requestId);
            tx.Rollback();
            throw;
        }
    }

    /// <inheritdoc />
    public async Task<int> DeleteAllCompletedAsync(CancellationToken ct = default)
    {
        var completed = await ListCompletedAsync(ct).ConfigureAwait(false);

        await using var conn = new SqliteConnection(NameAndPaths.DataFolder.WorkflowsFile.ConnectionString);
        await conn.OpenAsync(ct).ConfigureAwait(false);
        await using var tx = conn.BeginTransaction();
        try
        {
            var deletedRequests = 0;
            foreach (var requestId in completed.Keys)
            {
                var jobs = await LoadGroupAsync(requestId).ConfigureAwait(false);
                if (jobs is null) continue;
                foreach (var job in jobs)
                    await DeleteInstanceAsync(conn, tx, job.Id, ct).ConfigureAwait(false);
                await studioRepository.DeleteRequestAsync(requestId, ct).ConfigureAwait(false);
                deletedRequests++;
            }

            tx.Commit();
            logger.LogInformation("Deleted {Count} completed/cancelled request(s).", deletedRequests);
            return deletedRequests;
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Failed to delete completed requests | Reason: DB transaction error");
            tx.Rollback();
            throw;
        }
    }

    #region Aggregation helpers

    private async Task<IReadOnlyDictionary<string, IReadOnlyList<WorkflowInstance>>> ListGroupsAsync()
    {
        // WorkflowCore 3.18.0 has no non-obsolete way to list every instance of a given workflow type:
        // GetWorkflowInstance(id) needs a known id, GetWorkflowInstances(ids) needs a known id set,
        // GetRunnableInstances only returns runnable ones, and ISearchIndex is a separate opt-in
        // full-text search provider (not registered here) — not a fit for this simple type+status query.
#pragma warning disable CS0612
        var all = await persistence
            .GetWorkflowInstances(null, nameof(JobWorkflow), null, null, 0, int.MaxValue)
            .ConfigureAwait(false);
#pragma warning restore CS0612
        return all
            .Where(wi => wi.Data is JobContext)
            .GroupBy(wi => ((JobContext)wi.Data).Persist.RequestId)
            .ToDictionary(g => g.Key, IReadOnlyList<WorkflowInstance> (g) => g.ToList());
    }

    private async Task<IReadOnlyList<WorkflowInstance>?> LoadGroupAsync(string requestId)
    {
        var groups = await ListGroupsAsync().ConfigureAwait(false);
        return groups.GetValueOrDefault(requestId);
    }

    private async Task<PartialResult> FanOutAsync(
        string requestId, IReadOnlyList<WorkflowInstance>? jobs, WorkflowStatus eligibleStatus,
        Func<string, Task<bool>> action, Status status)
    {
        if (jobs is null) return new PartialResult(0, 0);

        var succeeded = 0;
        var skipped = 0;
        foreach (var job in jobs)
        {
            if (job.Status != eligibleStatus)
            {
                skipped++;
                continue;
            }

            var ok = await action(job.Id).ConfigureAwait(false);
            if (ok)
            {
                succeeded++;
                eventBus.Publish(new JobProgress
                {
                    RequestId = requestId,
                    JobId = job.Id,
                    Status = status,
                    Timestamp = DateTimeOffset.UtcNow
                });
            }
            else
            {
                skipped++;
            }
        }

        return new PartialResult(succeeded, skipped);
    }

    internal static List<JobSpecification> BuildJobs(Recipe.Models.Recipe recipe, Request request)
    {
        var jobs = new List<JobSpecification>();
        var mapNodes = recipe.Nodes
            .Where(kvp => kvp.Value is MapNode)
            .Select(kvp => (kvp.Key, (MapNode)kvp.Value));
        foreach (var (mapId, _) in mapNodes)
        {
            var incomingIds = recipe.Edges
                .Where(e => e.ToId == mapId)
                .Select(e => e.FromId)
                .ToHashSet();

            var slideNodeId = recipe.Edges
                .Where(e => e.FromId == mapId)
                .Select(e => e.ToId)
                .FirstOrDefault(id => recipe.Nodes.ContainsKey(id) && recipe.Nodes[id] is SlideNode);

            var presentationEntry = slideNodeId != null
                ? recipe.Nodes.FirstOrDefault(kvp =>
                    kvp.Value is PresentationNode pn && pn.SlideIds.Contains(slideNodeId))
                : default;

            if (slideNodeId == null || presentationEntry.Key == null) continue;

            foreach (var (workbookNodeId, workbookNode) in recipe.Nodes
                         .Where(kvp => kvp.Value is WorkbookNode)
                         .Select(kvp => (kvp.Key, (WorkbookNode)kvp.Value)))
            {
                foreach (var wsId in workbookNode.WorksheetIds.Where(incomingIds.Contains))
                {
                    if (recipe.Nodes[wsId] is not WorksheetNode worksheetNode) continue;

                    var bookName = Path.GetFileNameWithoutExtension(workbookNode.Workbook.BookPath);
                    var outputFileName =
                        $"{Naming.SanitizeFileName(worksheetNode.Worksheet.SheetName)}{request.OutputType.ToExtension()}";
                    var outputPath = Path.Combine(request.SaveFolder, bookName, outputFileName);

                    jobs.Add(new JobSpecification
                    {
                        Source = new WorkbookRef(workbookNodeId, wsId),
                        Template = new PresentationRef(presentationEntry.Key, slideNodeId),
                        MapNodeId = mapId,
                        OutputPath = outputPath
                    });
                }
            }
        }

        return jobs;
    }

